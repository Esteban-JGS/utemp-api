-- Initial schema for UTEMP. Matches the JPA entities in org.una.programmingIII.UTEMP_Project.models
-- (Hibernate runs with ddl-auto=validate, so any drift fails at startup).

CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(100) NOT NULL,
    email                 VARCHAR(150) NOT NULL,
    password              VARCHAR(128) NOT NULL,
    identification_number VARCHAR(50),
    role                  VARCHAR(255) NOT NULL,
    state                 VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    permissions           VARCHAR(800) NOT NULL,
    created_at            TIMESTAMP(6) NOT NULL,
    last_update           TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_users_identification_number UNIQUE (identification_number),
    CONSTRAINT ck_users_role CHECK (role IN ('STUDENT', 'TEACHER', 'ADMIN')),
    CONSTRAINT ck_users_state CHECK (state IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'DEPRECATED'))
);

CREATE TABLE universities (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    location    VARCHAR(200),
    created_at  TIMESTAMP(6) NOT NULL,
    last_update TIMESTAMP(6) NOT NULL
);

CREATE TABLE faculties (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50)  NOT NULL,
    university_id BIGINT       NOT NULL REFERENCES universities (id),
    created_at    TIMESTAMP(6) NOT NULL,
    last_update   TIMESTAMP(6) NOT NULL
);

CREATE TABLE departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50)  NOT NULL,
    faculty_id  BIGINT       NOT NULL REFERENCES faculties (id),
    created_at  TIMESTAMP(6) NOT NULL,
    last_update TIMESTAMP(6) NOT NULL
);

CREATE TABLE courses (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(50)  NOT NULL,
    description   VARCHAR(500) NOT NULL,
    teacher_id    BIGINT       NOT NULL REFERENCES users (id),
    department_id BIGINT       NOT NULL REFERENCES departments (id),
    state         VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP(6) NOT NULL,
    last_update   TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_courses_state CHECK (state IN ('ACTIVE', 'INACTIVE', 'ARCHIVED'))
);

CREATE TABLE enrollments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   BIGINT       NOT NULL REFERENCES courses (id),
    student_id  BIGINT       NOT NULL REFERENCES users (id),
    state       VARCHAR(255) NOT NULL DEFAULT 'ENROLLED',
    created_at  TIMESTAMP(6) NOT NULL,
    last_update TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_enrollments_state CHECK (state IN ('ENROLLED', 'DROPPED', 'COMPLETED'))
);

CREATE TABLE assignments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(100)  NOT NULL,
    description VARCHAR(1000) NOT NULL,
    deadline    TIMESTAMP(6) WITH TIME ZONE,
    course_id   BIGINT        NOT NULL REFERENCES courses (id),
    state       VARCHAR(255)  NOT NULL DEFAULT 'PENDING',
    created_at  TIMESTAMP(6)  NOT NULL,
    last_update TIMESTAMP(6)  NOT NULL,
    CONSTRAINT ck_assignments_state CHECK (state IN ('PENDING', 'ONGOING', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE submissions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assignment_id BIGINT       NOT NULL REFERENCES assignments (id),
    student_id    BIGINT       NOT NULL REFERENCES users (id),
    file_name     VARCHAR(255) NOT NULL,
    grade         DOUBLE PRECISION,
    comments      VARCHAR(500),
    state         VARCHAR(255) NOT NULL DEFAULT 'SUBMITTED',
    created_at    TIMESTAMP(6) NOT NULL,
    last_update   TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_submissions_state CHECK (state IN ('SUBMITTED', 'GRADED', 'REVISED', 'RESUBMITTED'))
);

CREATE TABLE grades (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id  BIGINT        NOT NULL REFERENCES submissions (id),
    grade          DOUBLE PRECISION,
    comments       VARCHAR(1000),
    reviewed_by_ai BOOLEAN,
    state          VARCHAR(255)  NOT NULL DEFAULT 'PENDING_REVIEW',
    created_at     TIMESTAMP(6)  NOT NULL,
    last_update    TIMESTAMP(6)  NOT NULL,
    CONSTRAINT ck_grades_state CHECK (state IN ('PENDING_REVIEW', 'FINALIZED'))
);

-- storage_path holds a server-generated name (UUID); file_name is the original name, kept only as metadata
CREATE TABLE file_metadata (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id BIGINT REFERENCES submissions (id),
    student_id    BIGINT REFERENCES users (id),
    file_name     VARCHAR(255) NOT NULL,
    file_type     VARCHAR(100),
    file_size     BIGINT       NOT NULL,
    storage_path  VARCHAR(500),
    created_at    TIMESTAMP(6) NOT NULL,
    last_update   TIMESTAMP(6) NOT NULL
);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT REFERENCES users (id),
    message     VARCHAR(500) NOT NULL,
    status      VARCHAR(255) NOT NULL DEFAULT 'UNREAD',
    created_at  TIMESTAMP(6) NOT NULL,
    last_update TIMESTAMP(6) NOT NULL,
    CONSTRAINT ck_notifications_status CHECK (status IN ('UNREAD', 'READ'))
);

-- Foreign keys are not indexed automatically in PostgreSQL
CREATE INDEX idx_faculties_university ON faculties (university_id);
CREATE INDEX idx_departments_faculty ON departments (faculty_id);
CREATE INDEX idx_courses_teacher ON courses (teacher_id);
CREATE INDEX idx_courses_department ON courses (department_id);
CREATE INDEX idx_enrollments_course ON enrollments (course_id);
CREATE INDEX idx_enrollments_student ON enrollments (student_id);
CREATE INDEX idx_assignments_course ON assignments (course_id);
CREATE INDEX idx_submissions_assignment ON submissions (assignment_id);
CREATE INDEX idx_submissions_student ON submissions (student_id);
CREATE INDEX idx_grades_submission ON grades (submission_id);
CREATE INDEX idx_file_metadata_submission ON file_metadata (submission_id);
CREATE INDEX idx_file_metadata_student ON file_metadata (student_id);
CREATE INDEX idx_notifications_user ON notifications (user_id);
